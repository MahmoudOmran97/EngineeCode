/**
 * يربط قائمتين (select) بحيث الثانية بتتحدث بمدن المحافظة المختارة في الأولى
 * @param {string} governorateSelectId  آي دي السيلكت بتاع المحافظة
 * @param {string} citySelectId         آي دي السيلكت بتاع المدينة/المركز
 */
function wireGovernorateCityDropdown(governorateSelectId, citySelectId) {
    var govSelect = document.getElementById(governorateSelectId);
    var citySelect = document.getElementById(citySelectId);
    if (!govSelect || !citySelect) return;

    function fillCities() {
        var gov = govSelect.value;
        citySelect.innerHTML = '';

        var placeholder = document.createElement('option');
        placeholder.value = '';
        citySelect.appendChild(placeholder);

        var cities = EGYPT_LOCATIONS[gov];
        if (!cities || !cities.length) {
            placeholder.textContent = 'اختر المحافظة أولاً';
            citySelect.disabled = true;
            return;
        }

        placeholder.textContent = 'اختر المدينة / المركز';
        citySelect.disabled = false;
        cities.forEach(function (city) {
            var opt = document.createElement('option');
            opt.value = city;
            opt.textContent = city;
            citySelect.appendChild(opt);
        });
    }

    govSelect.addEventListener('change', fillCities);
    fillCities(); // تهيئة أولية
}
